type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
  questionText: (number: number, english: string) => string;
  sectionText: (english: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return localStorage.getItem("detectives_language") === "rw" ? "rw" : "en";
    } catch {
      return "en";
    }
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    try {
      localStorage.setItem("detectives_language", nextLanguage);
    } catch {
      // Language selection remains active for this page session.
    }
  };

  useEffect(() => {
    document.documentElement.lang = language === "rw" ? "rw" : "en";
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (text) => (language === "rw" ? translations[text] ?? text : text),
      questionText: (number, english) =>
        language === "rw" ? questionTranslations[number] ?? english : english,
      sectionText: (english) =>
        language === "rw" ? sections[english] ?? english : english,
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
